#!/bin/bash
# Сдать работу одним шагом: запись в ящик следующего по цепочке с уликой.
#   bash сдать.sh <кому> <от> <репо> <коммит> "<что сдаю>" [файл-вывода-готовности]
# Кому: исполнитель → проверяющий (чекер, ревьюер); проверяющий с «чисто» → ведущий.
# Ящик адресата должен существовать (установка создаёт ящики владельца, ведущего и
# ролей). Пишет запись через запись.sh (время из часов, коммит): хеш, ветка,
# последние строки вывода команды готовности. Сообщений скрипт не шлёт: адресата
# зовёт вызвавший (с одной живой сессией — просто вызовом роли). Переменные латиницей.
set -eu
[ "$#" -ge 5 ] || { echo "сдать.sh: <кому> <от> <репо> <коммит> \"<что>\" [файл-вывода]" >&2; exit 64; }
TO="$1"; FROM="$2"; REPO="$3"; HASH="$4"; WHAT="$5"; OUT="${6:-}"
HERE="$(cd "$(dirname "$0")" && pwd)"
SHORT="$(git -C "$REPO" rev-parse --short "$HASH")"
BRANCH="$(git -C "$REPO" branch -a --contains "$HASH" --format='%(refname:short)' | head -3 | tr '\n' ' ')"
SUBJ="$(git -C "$REPO" log -1 --format=%s "$HASH")"
{
  echo "**Сдаю:** $WHAT"
  echo "Репозиторий: \`$REPO\`, коммит \`$SHORT\` («$SUBJ»), ветки: $BRANCH"
  if [ -n "$OUT" ] && [ -f "$OUT" ]; then echo "Готовность (хвост вывода):"; echo '```'; tail -8 "$OUT"; echo '```'; fi
  echo "Передано скриптом сдать.sh."
} | sh "$HERE/запись.sh" "$TO" "$FROM" "сдаю: $WHAT ($SHORT)"
echo "сдать.sh: записано в ящик $TO ($SHORT); дальше вызывающий зовёт $TO (для отдельной сессии — строка «дописал в ящик $TO — $SHORT»)"
